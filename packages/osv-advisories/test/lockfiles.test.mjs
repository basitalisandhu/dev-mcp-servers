import { test } from "node:test";
import assert from "node:assert/strict";
import { detectFormat, parseLockfile } from "../dist/lockfiles.js";

const CARGO = `# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "example"
version = "1.2.3"
source = "registry+https://github.com/rust-lang/crates.io-index"

[[package]]
name = "local"
version = "0.1.0"

[[package]]
name = "git-package"
version = "1.0.0"
source = "git+https://example.com/repo#123"

[[package]]
name = "incomplete"
source = "registry+https://index.crates.io/"
`;
const GEMFILE = `GIT
  remote: https://example.com/repo
  specs:
    git-gem (9.0.0)

GEM
  remote: https://rubygems.org/
  specs:
    example (1.2.3)
      dependency (~> 2)
    dependency (2.1.0)
    native (3.2.1-x86_64-linux)
    example (1.2.3)

PLATFORMS
  x86_64-linux

DEPENDENCIES
  example (~> 1.0)
`;

test("detects Cargo and Gemfile by filename and content without reclassifying Poetry", () => {
  assert.equal(detectFormat("/tmp/Cargo.lock", ""), "cargo");
  assert.equal(detectFormat("C:\\repo\\Gemfile.lock", ""), "gemfile");
  assert.equal(detectFormat(undefined, CARGO), "cargo");
  assert.equal(detectFormat(undefined, GEMFILE), "gemfile");
  assert.equal(detectFormat(undefined, '[[package]]\nname = "requests"\nversion = "2.0.0"\n'), "poetry");
});

test("Cargo returns registry pins and explains path, git and incomplete packages", () => {
  const result = parseLockfile(CARGO, "cargo");
  assert.deepEqual(result.packages, [{ ecosystem: "crates.io", name: "example", version: "1.2.3" }]);
  assert.equal(result.skipped.length, 3);
  assert.match(result.skipped.find((s) => s.entry === "local").reason, /source|path/);
  assert.match(result.skipped.find((s) => s.entry === "git-package").reason, /source|registry/);
  assert.match(result.skipped.find((s) => s.entry === "incomplete").reason, /version/);
});

test("Gemfile includes only GEM specs, not constraints or git/path packages", () => {
  const result = parseLockfile(GEMFILE, "gemfile");
  assert.deepEqual(result.packages, [
    { ecosystem: "RubyGems", name: "example", version: "1.2.3" },
    { ecosystem: "RubyGems", name: "dependency", version: "2.1.0" },
    { ecosystem: "RubyGems", name: "native", version: "3.2.1" },
  ]);
  assert.equal(result.skipped.length, 1);
  assert.equal(result.skipped[0].entry, "git-gem");
});

test("detects formats by name and by content", () => {
  assert.equal(detectFormat("package-lock.json", ""), "package-lock");
  assert.equal(detectFormat("/x/poetry.lock", ""), "poetry");
  assert.equal(detectFormat("go.sum", ""), "go-sum");
  assert.equal(detectFormat("dev-requirements.txt", ""), "requirements");
  assert.equal(detectFormat(undefined, '{"name":"a","lockfileVersion":2}'), "package-lock");
  assert.equal(detectFormat(undefined, '[[package]]\nname = "a"'), "poetry");
  assert.equal(detectFormat(undefined, "golang.org/x/text v0.3.0 h1:abc=\n"), "go-sum");
  assert.equal(detectFormat(undefined, "requests==2.0\n"), "requirements");
  assert.equal(detectFormat(undefined, "hello"), undefined);
});

test("poetry.lock and go.sum parse to exact pins", () => {
  const poetry = parseLockfile('[[package]]\nname = "Requests"\nversion = "2.31.0"\n\n[package.extras]\nsocks = []\n\n[[package]]\nname = "idna"\nversion = "3.4"\n', "poetry");
  assert.deepEqual(poetry.packages, [{ ecosystem: "PyPI", name: "requests", version: "2.31.0" }, { ecosystem: "PyPI", name: "idna", version: "3.4" }]);
  const gosum = parseLockfile("golang.org/x/text v0.3.0 h1:a=\ngolang.org/x/text v0.3.0/go.mod h1:b=\nbad line\n", "go-sum");
  assert.deepEqual(gosum.packages, [{ ecosystem: "Go", name: "golang.org/x/text", version: "0.3.0" }]);
  assert.equal(gosum.skipped.length, 1);
});

test("package-lock v1 dependencies tree is walked", () => {
  const v1 = parseLockfile(JSON.stringify({ lockfileVersion: 1, dependencies: { a: { version: "1.0.0", dependencies: { b: { version: "2.0.0" } } }, c: { version: "file:../c" } } }), "package-lock");
  assert.deepEqual(v1.packages.map((p) => p.name), ["a", "b"]);
  assert.equal(v1.skipped[0].entry, "c");
  assert.throws(() => parseLockfile("{", "package-lock"), /not valid JSON/);
});
